/// Where Boney's skull sits in [sprite], as a shift from the front pose
/// (its top row at (12, 4)): the first five-wide run with the nine-wide
/// row of the skull right under it. (0, 0) when there is none.
(int, int) skullShift(PixelSprite sprite) => _shifts[sprite] ??= () {
  final rows = sprite.rows;
  for (var y = 0; y + 1 < rows.length; y++) {
    final top = rows[y];
    for (var x = 2; x + 7 <= top.length && x + 7 <= rows[y + 1].length; x++) {
      if (top.substring(x, x + 5) != '#####') continue;
      if (x + 5 < top.length && top[x + 5] == '#') continue;
      if (top[x - 1] == '#') continue;
      if (rows[y + 1].substring(x - 2, x + 7) == '#########') {
        return (x - 12, y - 4);
      }
    }
  }
  return (0, 0);
}();

final _shifts = Expando<(int, int)>();
